"""Build .env.server for the production server from the working local .env.

Copies the owner, WhatsApp and LLM values, and sets server-only values:
a new database password, production mode, real WhatsApp sending, the
domain and certificate email, and the compose files to use.

Usage: uv run python scripts/make_server_env.py --domain ai.example.com --email you@example.com
Writes .env.server with permissions 0600. It is git-ignored; never commit it.
"""

from __future__ import annotations

import argparse
import os
import re
import secrets
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
COPY_KEYS = [
    "OWNER_NAME", "OWNER_WHATSAPP_NUMBER", "OWNER_EMAIL",
    "WHATSAPP_ACCESS_TOKEN", "WHATSAPP_PHONE_NUMBER_ID", "WHATSAPP_VERIFY_TOKEN", "WHATSAPP_APP_SECRET",
    "WHATSAPP_API_VERSION", "WHATSAPP_TEMPLATE_NAME", "WHATSAPP_TEMPLATE_LANG", "OUTBOUND_MAX_PER_10MIN",
    "LLM_BACKEND", "LLM_CONCURRENCY",
    "ANTHROPIC_API_KEY", "ANTHROPIC_MODEL", "ANTHROPIC_EFFORT",
    "DAILY_SUMMARY_TIME", "MAX_UPLOAD_MB", "TIMEZONE", "LOG_LEVEL",
]
REQUIRED = ["OWNER_WHATSAPP_NUMBER", "WHATSAPP_ACCESS_TOKEN", "WHATSAPP_PHONE_NUMBER_ID",
            "WHATSAPP_VERIFY_TOKEN", "WHATSAPP_APP_SECRET"]
DOMAIN_RE = re.compile(r"^(?=.{4,253}$)([a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,}$")


def read_env(path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    for line in path.read_text().splitlines():
        if not line.strip() or line.lstrip().startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        values[key.strip()] = value.strip()
    return values


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--domain", required=True, help="e.g. ai.example.com (no https://)")
    ap.add_argument("--email", required=True, help="address for Let's Encrypt certificate notices")
    ap.add_argument("--source", default=str(ROOT / ".env"))
    ap.add_argument("--out", default=str(ROOT / ".env.server"))
    ap.add_argument("--force", action="store_true", help="overwrite an existing output file")
    args = ap.parse_args()

    domain = args.domain.lower().removeprefix("https://").removeprefix("http://").strip("/")
    if not DOMAIN_RE.match(domain):
        sys.exit(f"Not a valid domain: {args.domain}")
    if "@" not in args.email:
        sys.exit(f"Not a valid email: {args.email}")
    out = Path(args.out)
    if out.exists() and not args.force:
        sys.exit(f"{out} already exists (use --force to replace it; that also changes the DB password)")

    src = read_env(Path(args.source))
    missing = [k for k in REQUIRED if not src.get(k)]
    if missing:
        sys.exit(f"Missing in {args.source}: {', '.join(missing)}")
    if src.get("LLM_BACKEND") == "anthropic_api" and not src.get("ANTHROPIC_API_KEY"):
        sys.exit("LLM_BACKEND=anthropic_api needs ANTHROPIC_API_KEY")

    pw = secrets.token_urlsafe(24)
    lines = [
        "# Generated by scripts/make_server_env.py. Keep private (chmod 600). Never commit.",
        "COMPOSE_FILE=docker-compose.yml:docker-compose.prod.yml",
        "APP_ENV=production",
        f"DOMAIN={domain}",
        f"ACME_EMAIL={args.email}",
        "",
        "POSTGRES_USER=kings",
        f"POSTGRES_PASSWORD={pw}",
        "POSTGRES_DB=kings_ai",
        f"DATABASE_URL=postgresql+psycopg://kings:{pw}@db:5432/kings_ai",
        "",
        "MESSAGING_BACKEND=meta",
        "FILE_STORAGE_DIR=/data/files",
        "BACKUP_DIR=/var/backups/kings-ai",
        "BACKUP_KEEP_DAYS=14",
        "# Optional off-server copy, e.g. BACKUP_RCLONE_REMOTE=r2:kings-ai-backups (needs rclone configured)",
        "BACKUP_RCLONE_REMOTE=",
        "",
    ]
    lines += [f"{k}={src[k]}" for k in COPY_KEYS if k in src]
    fd = os.open(out, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    os.chmod(out, 0o600)
    print(f"Wrote {out} (0600) for {domain}. LLM backend: {src.get('LLM_BACKEND', 'anthropic_api')}.")


if __name__ == "__main__":
    main()
